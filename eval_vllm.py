#!/usr/bin/env python3
"""Batched vLLM evaluation for Qwen2.5-VL and LLaVA on MLLMU-Bench.

The task construction, prompts, scoring, split semantics, and JSON schema match
``eval.py``. Only the generation backend is replaced with vLLM so requests can
be scheduled in batches.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import ast
import tempfile
from dataclasses import dataclass
from io import BytesIO
from pathlib import Path
from typing import Any

import pandas as pd
from PIL import Image
from rouge_score import rouge_scorer
# LLaVA's slow SentencePiece tokenizer in the opsd environment uses protobuf
# descriptors generated by an older protoc. Set the documented compatibility
# mode before importing Transformers/SentencePiece. It is harmless for Qwen.
os.environ.setdefault("PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION", "python")

from transformers import AutoConfig, AutoProcessor, GenerationConfig

import eval_vllm_benchmark as benchmark


@dataclass
class Job:
    question: str
    image: Image.Image | None
    metadata: dict[str, Any]


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model_id", required=True, help="Model family ID/path used to select the prompt template.")
    parser.add_argument("--cache_path", help="Local trained checkpoint; required unless --pretrain is set.")
    parser.add_argument("--processor_path", help="Processor ID/path when it is separate from model weights.")
    parser.add_argument("--pretrain", action="store_true", help="Evaluate --model_id directly.")
    parser.add_argument("--data_split_folder", required=True)
    parser.add_argument("--task_data", default=str(benchmark.DEFAULT_TASK_DATA))
    parser.add_argument("--test_data", required=True)
    parser.add_argument("--celebrity_data", required=True)
    parser.add_argument("--output_folder", required=True)
    parser.add_argument("--output_file", required=True)
    parser.add_argument("--forget_ratio", type=int, default=5)
    parser.add_argument("--max_eval_samples", type=int)
    parser.add_argument("--max_questions_per_group", type=int)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--batch_size", type=int, default=32)
    parser.add_argument("--max_new_tokens", type=int, default=50)
    parser.add_argument("--max_model_len", type=int, default=8192)
    parser.add_argument(
        "--attn_implementation",
        choices=("flash_attention_2", "sdpa", "eager"),
        default="flash_attention_2",
        help="Compatibility argument; vLLM uses its Flash Attention backend.",
    )
    parser.add_argument("--tensor_parallel_size", type=int, default=1)
    parser.add_argument("--gpu_memory_utilization", type=float, default=0.90)
    parser.add_argument("--dtype", choices=("auto", "float16", "bfloat16"), default="auto")
    parser.add_argument("--enforce_eager", action="store_true")
    return parser.parse_args()


def validate_args(args):
    if not args.pretrain and not args.cache_path:
        raise ValueError("--cache_path is required unless --pretrain is used")
    if not 1 <= args.forget_ratio <= 99:
        raise ValueError("--forget_ratio must be between 1 and 99")
    for name in ("batch_size", "max_model_len", "tensor_parallel_size"):
        if getattr(args, name) < 1:
            raise ValueError(f"--{name} must be positive")
    if args.max_new_tokens < 1:
        raise ValueError("--max_new_tokens must be positive")
    for name in ("max_eval_samples", "max_questions_per_group"):
        value = getattr(args, name)
        if value is not None and value < 1:
            raise ValueError(f"--{name} must be positive when provided")


def resolve_processor_source(source: str) -> str:
    if Path(source).is_dir():
        return str(Path(source).resolve())
    from huggingface_hub import snapshot_download

    try:
        return snapshot_download(source, local_files_only=True)
    except FileNotFoundError:
        return snapshot_download(source)


def combined_model_view(model_source: str, processor_source: str) -> str:
    """Give vLLM one directory containing both weights and MM processor files."""
    model_dir = Path(model_source).resolve()
    processor_dir = Path(processor_source).resolve()
    if not model_dir.is_dir() or not processor_dir.is_dir():
        return model_source
    required = ("preprocessor_config.json", "tokenizer_config.json")
    if all((model_dir / name).exists() for name in required):
        return str(model_dir)

    view = model_dir.parent / f".{model_dir.name}_vllm_processor_view"
    view.mkdir(exist_ok=True)
    for source_dir in (model_dir, processor_dir):
        for item in source_dir.iterdir():
            target = view / item.name
            if not target.exists() and not target.is_symlink():
                target.symlink_to(item)
    return str(view)


class VLLMBackend:
    def __init__(self, args):
        from vllm import LLM

        self.args = args
        self.merged_dir = None
        self.model_source = args.model_id if args.pretrain else args.cache_path
        self.lora_path = None
        if not args.pretrain and Path(self.model_source).is_dir() and (Path(self.model_source) / "adapter_config.json").exists():
            with open(Path(self.model_source) / "adapter_config.json") as f:
                adapter_cfg = json.load(f)
            base_source = adapter_cfg.get("base_model_name_or_path") or str(Path("llava_smu_ft").resolve())
            merged_dir = Path(self.model_source).parent / f".{Path(self.model_source).name}_vllm_merged"
            self.merged_dir = merged_dir
            if not (merged_dir / "model.safetensors.index.json").exists():
                from peft import PeftModel
                from transformers import LlavaForConditionalGeneration
                print(f"Merging LoRA adapter into {base_source} for vLLM...", flush=True)
                base = LlavaForConditionalGeneration.from_pretrained(
                    base_source, torch_dtype="auto", low_cpu_mem_usage=True,
                    local_files_only=Path(base_source).is_dir())
                merged = PeftModel.from_pretrained(base, self.model_source).merge_and_unload()
                merged.save_pretrained(merged_dir, safe_serialization=True, max_shard_size="5GB")
                processor_dir = Path(args.processor_path or base_source).resolve()
                if processor_dir.is_dir():
                    for item in processor_dir.iterdir():
                        target = merged_dir / item.name
                        if not target.exists() and not target.is_symlink():
                            target.symlink_to(item.resolve())
            self.model_source = str(merged_dir)
        config = AutoConfig.from_pretrained(
            self.model_source,
            local_files_only=Path(self.model_source).is_dir(),
        )
        model_type = getattr(config, "model_type", "")
        if model_type == "qwen2_5_vl":
            self.kind = "qwen"
        elif model_type.startswith("llava"):
            self.kind = "llava"
        else:
            raise ValueError(f"Unsupported model_type={model_type!r}; expected Qwen2.5-VL or LLaVA")

        if args.processor_path:
            processor_id = args.processor_path
        elif self.kind == "qwen" and Path("Qwen_Vanilla/processor").is_dir():
            processor_id = "Qwen_Vanilla/processor"
        else:
            processor_id = args.model_id
        self.processor_source = resolve_processor_source(processor_id)
        # Match eval.py's Transformers 4.51 preprocessing instead of the fast
        # processor that newer Transformers versions enable by default.
        self.processor = AutoProcessor.from_pretrained(
            self.processor_source,
            local_files_only=True,
            use_fast=False,
        )
        self.processor.tokenizer.padding_side = "left"
        try:
            generation_config = GenerationConfig.from_pretrained(
                self.model_source,
                local_files_only=Path(self.model_source).is_dir(),
            )
        except (OSError, ValueError):
            # Some merged training checkpoints omit generation_config.json;
            # use the matching vanilla checkpoint's config in that case.
            fallback = "Qwen_Vanilla" if self.kind == "qwen" else "LLaVA_Vanilla"
            generation_config = GenerationConfig.from_pretrained(
                fallback,
                local_files_only=True,
            )
        self.repetition_penalty = float(
            getattr(generation_config, "repetition_penalty", 1.0) or 1.0
        )
        eos_token_id = getattr(generation_config, "eos_token_id", None)
        if isinstance(eos_token_id, int):
            self.stop_token_ids = [eos_token_id]
        else:
            self.stop_token_ids = list(eos_token_id or [])

        engine_source = combined_model_view(self.model_source, self.processor_source)
        dtype = args.dtype
        if dtype == "auto":
            dtype = "bfloat16" if self.kind == "qwen" else "float16"
        print(f"Loading {self.kind} with vLLM from {engine_source}")
        try:
            self.llm = LLM(
                model=engine_source,
                tokenizer=engine_source,
                dtype=dtype,
                tensor_parallel_size=args.tensor_parallel_size,
                max_model_len=args.max_model_len,
                gpu_memory_utilization=args.gpu_memory_utilization,
                limit_mm_per_prompt={"image": 1},
                mm_processor_kwargs={"use_fast": False, "num_additional_image_tokens": 1},
                enforce_eager=True,
            )
        except Exception:
            self.cleanup()
            raise

    def cleanup(self):
        """Remove the temporary merged LoRA model created for vLLM."""
        if self.merged_dir is None:
            return
        import shutil
        if self.merged_dir.exists() or self.merged_dir.is_symlink():
            print(f"Removing temporary merged model: {self.merged_dir}", flush=True)
            if self.merged_dir.is_dir() and not self.merged_dir.is_symlink():
                shutil.rmtree(self.merged_dir, ignore_errors=True)
            else:
                self.merged_dir.unlink(missing_ok=True)

    def prompt(self, question: str, image: Image.Image | None) -> str:
        if self.kind == "qwen":
            content = []
            if image is not None:
                content.append({"type": "image"})
            content.append({"type": "text", "text": question})
            return self.processor.apply_chat_template(
                [{"role": "user", "content": content}],
                tokenize=False,
                add_generation_prompt=True,
            )
        return benchmark.build_zero_shot_prompt(question, image is not None)

    def generate(self, jobs: list[Job], max_tokens: int) -> list[str]:
        from vllm import SamplingParams

        if not jobs:
            return []
        params = SamplingParams(
            temperature=0.0,
            max_tokens=max_tokens,
            repetition_penalty=self.repetition_penalty,
            stop_token_ids=self.stop_token_ids,
            seed=self.args.seed,
        )
        answers: list[str] = []
        for offset in range(0, len(jobs), self.args.batch_size):
            chunk = jobs[offset:offset + self.args.batch_size]
            requests = []
            for job in chunk:
                request: dict[str, Any] = {"prompt": self.prompt(job.question, job.image)}
                if job.image is not None:
                    request["multi_modal_data"] = {"image": job.image}
                requests.append(request)
            outputs = self.llm.generate(requests, params, use_tqdm=False)
            for output in outputs:
                text = output.outputs[0].text.strip() if output.outputs else ""
                for marker in ("ASSISTANT:", "Answer:"):
                    if marker in text:
                        text = text.rsplit(marker, 1)[-1].strip()
                answers.append(text)
            print(f"Generated {min(offset + len(chunk), len(jobs))}/{len(jobs)}", flush=True)
        return answers


def evaluation_rows(path: str, mode: str, forget_file: str, args):
    files = sorted(Path(path).glob("*.parquet")) if Path(path).is_dir() else [Path(path)]
    df = pd.concat([pd.read_parquet(file) for file in files], ignore_index=True)
    if mode == "test":
        forget_ids = pd.read_parquet(forget_file)["ID"].unique().tolist()
        df = df[df["ID"].isin(forget_ids)]
    if args.max_eval_samples is not None:
        df = df.head(args.max_eval_samples)
    def convert(value):
        if isinstance(value, str):
            return ast.literal_eval(value)
        return value
    rows = []
    for _, row in df.iterrows():
        item = row.copy()
        classify = convert(row.get("Classify", "{}"))
        cloze = convert(row.get("Cloze", "{}"))
        generation = convert(row.get("Generation", "{}"))
        item["Classification_Task"] = {
            "Image_Textual_Questions": [{"Question": v.get("question", ""), "Options": v.get("options", {}), "Correct_Answer": v.get("answer", ""), "Type": "Image_Textual"} for v in classify.get("muitimodal", {}).values()],
            "Pure_Text_Questions": [{"Question": v.get("question", ""), "Options": v.get("options", {}), "Correct_Answer": v.get("answer", ""), "Type": "Pure_Text"} for v in classify.get("unimodal", {}).values()],
        }
        item["Mask_Task"] = [
            {"Question": v.get("question", ""), "Ground_Truth": v.get("answer", ""), "Type": "Image_Textual"}
            for v in cloze.get("muitimodal", {}).values()
        ] + [
            {"Question": v.get("question", ""), "Ground_Truth": v.get("answer", ""), "Type": "Pure_Text"}
            for v in cloze.get("unimodal", {}).values()
        ]
        item["Generation_Task"] = [
            {"Question": v.get("question", ""), "Ground_Truth": v.get("answer", ""), "Type": "Image_Textual"}
            for v in generation.get("muitimodal", {}).values()
        ] + [
            {"Question": v.get("question", ""), "Ground_Truth": v.get("answer", ""), "Type": "Pure_Text"}
            for v in generation.get("unimodal", {}).values()
        ]
        rows.append(item)
    return pd.DataFrame(rows)


def questions(items, args):
    values = list(items)
    if args.max_questions_per_group is not None:
        values = values[:args.max_questions_per_group]
    return values


def row_image(row, mode):
    data = row["image"].get("bytes")
    return Image.open(BytesIO(data)).convert("RGB")


def classification_jobs(path, mode, forget_file, args):
    jobs = []
    skipped = {"Image_Textual": 0, "Pure_Text": 0}
    for _, row in evaluation_rows(path, mode, forget_file, args).iterrows():
        image = row_image(row, mode)
        groups = row["Classification_Task"]
        for group_name in ("Image_Textual_Questions", "Pure_Text_Questions"):
            question_type = "Image_Textual" if group_name.startswith("Image") else "Pure_Text"
            for item in questions(groups.get(group_name, []), args):
                try:
                    options, correct = benchmark.classification_answers(
                        item["Options"], item["Correct_Answer"]
                    )
                except benchmark.InvalidClassificationAnswer as exc:
                    skipped[question_type] += 1
                    print(f"Skipping invalid classification question for ID {row['ID']}: {exc}")
                    continue
                jobs.append(Job(
                    question=f"{item['Question']}\nSelect answer in {options}",
                    image=image if question_type == "Image_Textual" else None,
                    metadata={"type": question_type, "correct": correct},
                ))
    return jobs, skipped


def evaluate_classification(backend, path, mode, forget_file, args):
    jobs, skipped = classification_jobs(path, mode, forget_file, args)
    answers = backend.generate(jobs, args.max_new_tokens)
    totals = {"Image_Textual": 0, "Pure_Text": 0}
    correct = {"Image_Textual": 0, "Pure_Text": 0}
    for job, answer in zip(jobs, answers):
        kind = job.metadata["type"]
        totals[kind] += 1
        correct[kind] += int(benchmark.answer_contains_correct_option(answer, job.metadata["correct"]))
    return {
        "Image-Textual Question Accuracy": 100 * correct["Image_Textual"] / totals["Image_Textual"] if totals["Image_Textual"] else 0,
        "Pure Text Question Accuracy": 100 * correct["Pure_Text"] / totals["Pure_Text"] if totals["Pure_Text"] else 0,
        "Skipped Invalid Image-Textual Questions": skipped["Image_Textual"],
        "Skipped Invalid Pure Text Questions": skipped["Pure_Text"],
    }


def fill_jobs(path, mode, forget_file, args):
    jobs = []
    for _, row in evaluation_rows(path, mode, forget_file, args).iterrows():
        image = row_image(row, mode)
        for item in questions(row["Mask_Task"], args):
            kind = item["Type"]
            prompt = item["Question"].replace("__", "[Blank]")
            prompt += "\nPlease **ONLY** provide the correct answer that should replace the [Blank]."
            jobs.append(Job(
                question=prompt,
                image=image if kind == "Image_Textual" else None,
                metadata={"type": kind, "ground_truth": item["Ground_Truth"]},
            ))
    return jobs


def evaluate_fill(backend, path, mode, forget_file, args):
    jobs = fill_jobs(path, mode, forget_file, args)
    answers = backend.generate(jobs, args.max_new_tokens)
    totals = {"Image_Textual": 0, "Pure_Text": 0}
    correct = {"Image_Textual": 0, "Pure_Text": 0}
    for job, answer in zip(jobs, answers):
        kind = job.metadata["type"]
        totals[kind] += 1
        correct[kind] += int(str(job.metadata["ground_truth"]).casefold() in answer.casefold())
    return {
        "image_textual_accuracy": 100 * correct["Image_Textual"] / totals["Image_Textual"] if totals["Image_Textual"] else 0,
        "pure_text_accuracy": 100 * correct["Pure_Text"] / totals["Pure_Text"] if totals["Pure_Text"] else 0,
    }


def generation_jobs(path, mode, forget_file, args):
    jobs = []
    for _, row in evaluation_rows(path, mode, forget_file, args).iterrows():
        image = row_image(row, mode)
        for item in questions(row["Generation_Task"], args):
            kind = item["Type"]
            prompt = item["Question"]
            prompt += "\nAnswer the question based on your trained knowledge in one sentence accurately in ENGLISH."
            jobs.append(Job(
                question=prompt,
                image=image if kind == "Image_Textual" else None,
                metadata={
                    "image_id": row["ID"],
                    "type": kind,
                    "question": item["Question"],
                    "ground_truth": item["Ground_Truth"],
                },
            ))
    return jobs


def evaluate_generation(backend, path, mode, forget_file, args):
    jobs = generation_jobs(path, mode, forget_file, args)
    answers = backend.generate(jobs, args.max_new_tokens)
    scorer = rouge_scorer.RougeScorer(["rouge1", "rouge2", "rougeL"], use_stemmer=True)
    metric_names = ("rouge1", "rouge2", "rougeL", "bleu")
    sums = {kind: {name: 0.0 for name in metric_names} for kind in ("Image_Textual", "Pure_Text")}
    counts = {"Image_Textual": 0, "Pure_Text": 0}
    details = {"Generation_Questions": []}
    for job, answer in zip(jobs, answers):
        kind = job.metadata["type"]
        truth = str(job.metadata["ground_truth"])
        scores = scorer.score(truth, answer)
        sums[kind]["rouge1"] += scores["rouge1"].fmeasure
        sums[kind]["rouge2"] += scores["rouge2"].fmeasure
        sums[kind]["rougeL"] += scores["rougeL"].fmeasure
        sums[kind]["bleu"] += benchmark.compute_bleu(truth, answer)
        counts[kind] += 1
        details["Generation_Questions"].append({
            "image_id": job.metadata["image_id"],
            "question type": kind,
            "question": job.metadata["question"],
            "generated_answer": answer,
            "ground_truth": truth,
        })

    output_dir = Path(args.output_folder)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / f"{mode}_generation_results.json").write_text(
        json.dumps(details, ensure_ascii=False, indent=4), encoding="utf-8"
    )
    result = {}
    for kind, label in (("Image_Textual", "Image_Textual"), ("Pure_Text", "Pure_Text")):
        if not counts[kind]:
            continue
        result.update({
            f"Average ROUGE-1 ({label})": sums[kind]["rouge1"] / counts[kind],
            f"Average ROUGE-2 ({label})": sums[kind]["rouge2"] / counts[kind],
            f"Average ROUGE-L ({label})": sums[kind]["rougeL"] / counts[kind],
            f"Average BLEU ({label})": sums[kind]["bleu"] / counts[kind],
        })
    return result


def evaluate_scope(backend, path, mode, forget_file, args):
    print(f"\n### Evaluating {mode}: {path} ###")
    fill = evaluate_fill(backend, path, mode, forget_file, args)
    classification = evaluate_classification(backend, path, mode, forget_file, args)
    generation = evaluate_generation(backend, path, mode, forget_file, args)
    return {"fill_in_the_blank": fill, "classification": classification, "generation": generation}


def main():
    args = parse_args()
    validate_args(args)
    random.seed(args.seed)
    forget_file = str(Path(args.data_split_folder) / f"forget_{args.forget_ratio}" / "train-00000-of-00001.parquet")
    retain_file = str(Path(args.data_split_folder) / f"retain_{100 - args.forget_ratio}" / "train-00000-of-00001.parquet")
    required = (forget_file, retain_file, args.test_data, args.celebrity_data, args.task_data)
    for path in required:
        if not Path(path).exists():
            raise FileNotFoundError(path)

    backend = VLLMBackend(args)
    try:
        results = {
            "Forget Set Results": evaluate_scope(backend, forget_file, "forget", forget_file, args),
            "Test Set Results": evaluate_scope(backend, args.test_data, "test", forget_file, args),
            "Retain Set (shared dataset) Results": evaluate_scope(backend, retain_file, "retain_shared", forget_file, args),
            "Retain Set (real person) Results": evaluate_scope(backend, args.celebrity_data, "retain_celebrity", forget_file, args),
        }
        output = Path(args.output_folder) / f"{args.output_file}_final_evaluation_results.json"
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(json.dumps(results, ensure_ascii=False, indent=4), encoding="utf-8")
        print(json.dumps(results, ensure_ascii=False, indent=2))
        print(f"Results saved to {output}")
    finally:
        backend.cleanup()


if __name__ == "__main__":
    main()
